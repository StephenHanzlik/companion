-- Replace the free-text trip zone with a US state, stored as its two-letter code.
ALTER TABLE trips DROP COLUMN zone;
ALTER TABLE trips ADD COLUMN state CHAR(2)
    CHECK (state IN (
        'AL','AK','AZ','AR','CA','CO','CT','DE','FL','GA',
        'HI','ID','IL','IN','IA','KS','KY','LA','ME','MD',
        'MA','MI','MN','MS','MO','MT','NE','NV','NH','NJ',
        'NM','NY','NC','ND','OH','OK','OR','PA','RI','SC',
        'SD','TN','TX','UT','VT','VA','WA','WV','WI','WY'
    ));
